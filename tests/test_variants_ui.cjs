const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path'),vm=require('node:vm');
const InventoryTools=require('../web/inventory-tools.js');
const limits=JSON.parse(fs.readFileSync(path.join(__dirname,'../backend/variant-limits.json'),'utf8'));
assert.equal(limits.CapeLinen,6);assert.equal(limits.ShieldWood,4);assert(limits.Hammer<=1);
const itemsById={ShieldWood:{variantCount:4,icons:['one.png','two.png','three.png','four.png']},Hammer:{variantCount:1,icons:['hammer.png']}};
const source=fs.readFileSync(path.join(__dirname,'../web/app.js'),'utf8');
const context={InventoryTools,itemsById,itemInfo:i=>itemsById[i.prefab]||{}};vm.createContext(context);
vm.runInContext(source.slice(source.indexOf('const icon='),source.indexOf('const fmt=')),context);
vm.runInContext(source.slice(source.indexOf('function variantControls('),source.indexOf('function renderInspector(')),context);
context.item={prefab:'ShieldWood',variant:0};
assert(vm.runInContext('icon(item)',context).includes('one.png'));
context.item.variant=2;assert(vm.runInContext('icon(item)',context).includes('three.png'));
assert(vm.runInContext('variantControls(item)',context).includes('data-variant="2" class="chosen"'));
assert(vm.runInContext('variantControls(item,true)',context).includes('data-container-variant="2"'));
context.item={prefab:'Hammer',variant:0};assert.equal(vm.runInContext('variantControls(item)',context),'');
assert(!InventoryTools.validVariant({prefab:'Hammer'},itemsById,0));
assert(!InventoryTools.validVariant({prefab:'ShieldWood'},itemsById,4));
assert.equal(InventoryTools.iconName({prefab:'ShieldWood',variant:99},itemsById),null);
itemsById.ShieldWood.icons[2]=null;context.item={prefab:'ShieldWood',variant:2};
assert(vm.runInContext('variantControls(item)',context).includes('Some style artwork is unavailable'));
assert(vm.runInContext('icon(item)',context).includes('fallback'));
console.log('Variant controls, selection, icon mapping and missing-art fallback passed.');
